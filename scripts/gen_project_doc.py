def para(text="", size=11, bold=False, color=None, align=None, space_after=6):
    p = doc.add_paragraph()
    if align:
        p.alignment = align
    r = p.add_run(text)
    r.font.size = Pt(size)
    r.font.bold = bold
    if color:
        r.font.color.rgb = color
    r.font.name = "微软雅黑"
    r.element.rPr.rFonts.set(qn("w:eastAsia"), "微软雅黑")
    p.paragraph_format.space_after = Pt(space_after)
    return p


def shot(desc):
    """截图占位框：灰底描边段落。"""
    p = para(f"【截图位置：{desc}】", size=10.5, bold=True, color=GRAY,
             align=WD_ALIGN_PARAGRAPH.CENTER, space_after=10)
    pPr = p._p.get_or_add_pPr()
    shd = OxmlElement("w:shd"); shd.set(qn("w:val"), "clear"); shd.set(qn("w:fill"), "F2F2F2")
    pPr.append(shd)
    pbdr = OxmlElement("w:pBdr")
    for side in ("top", "bottom", "left", "right"):
        b = OxmlElement(f"w:{side}")
        b.set(qn("w:val"), "dashed"); b.set(qn("w:sz"), "6"); b.set(qn("w:color"), "999999")
        pbdr.append(b)
    pPr.append(pbdr)


def table(headers, rows, widths=None):
    t = doc.add_table(rows=1, cols=len(headers))
    t.style = "Table Grid"
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    for j, h in enumerate(headers):
        cell = t.rows[0].cells[j]
        cell.text = ""
        r = cell.paragraphs[0].add_run(h)
        r.font.bold = True; r.font.size = Pt(10.5)
        r.font.name = "微软雅黑"; r.element.rPr.rFonts.set(qn("w:eastAsia"), "微软雅黑")
        shd = OxmlElement("w:shd"); shd.set(qn("w:val"), "clear"); shd.set(qn("w:fill"), "DEEAF6")
        cell._tc.get_or_add_tcPr().append(shd)
    for row in rows:
        cells = t.add_row().cells
        for j, v in enumerate(row):
            cells[j].text = ""
            r = cells[j].paragraphs[0].add_run(str(v))
            r.font.size = Pt(10)
            r.font.name = "微软雅黑"; r.element.rPr.rFonts.set(qn("w:eastAsia"), "微软雅黑")
    doc.add_paragraph().paragraph_format.space_after = Pt(2)
    return t


